'''Write a function multiply(a, b) that has a proper docstring
 explaining what it does. Then use help(multiply) to display 
 the docstring.'''

def multiply(a,b):
    """ 
    Returns the sum of two numbers.

    Parameters:
    a (int): The first number.
    b (int): The second number.

    Returns:
    int: The sum of the two numbers."""
    return (a*b)

print(help(multiply))