# Positive Indexing
name = "Harry"
print(name[0])
print(name[1])
print(name[2])
print(name[3])
print(name[4])

# Negative Indexing
print(name[-1])
print(name[-2])
print(name[-3])
print(name[-4])
print(name[-5])
# To convert negative indexing to positive indeexing add the negative index to the size of string.
