#  They are simple one liner functions in python.

square =  lambda x : x*x
''' It is as good as writing
    def square(x):
        return(x*x)'''

print(square(4))
print(square(94))
print(square(45))
print(square(7))
print(square(8))
print(square(6))
print(square(5))

add = lambda x,y,z : x+y+z
'''It is as good as writing
    def add(x,y,z):
        return(x+y+z)'''
 
print(add(23,45,78))